        // AES INVERSE CIPHER
        // =============================================================

        // INV_KEY0..INV_KEY3 = same AES key
        axi_write(8'h48, key[31:0]);
        axi_write(8'h4C, key[63:32]);
        axi_write(8'h50, key[95:64]);
        axi_write(8'h54, key[127:96]);

        // Inverse input = ciphertext from the current vector
        axi_write(8'h68, ciph[31:0]);
        axi_write(8'h6C, ciph[63:32]);
        axi_write(8'h70, ciph[95:64]);
        axi_write(8'h74, ciph[127:96]);

        // INV_CSR[17]=KLD, INV_CSR[16]=LD
        axi_write(8'h44, 32'h0003_0000);

        // Wait for inverse cipher completion
        while (!inv_done)
            @(posedge clk);

        // =============================================================
        // Read INVERSE TEXT_OUT0..3 through AXI
        // =============================================================
        axi_read(8'h78, rd);
        if (rd !== plain[31:0]) begin
            $display("ERROR: Inverse Vector %0d TEXT_OUT0 mismatch. Expected %h, Got %h",
                     n, plain[31:0], rd);
            error_cnt = error_cnt + 1;
