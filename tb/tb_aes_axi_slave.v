// -----------------------------------------------------------------------------
// Clock
// -----------------------------------------------------------------------------
always #5 clk = ~clk;

// -----------------------------------------------------------------------------
// AXI4-Lite write
// -----------------------------------------------------------------------------
task automatic axi_write;
    input [AXI_ADDR_WIDTH-1:0] addr;
    input [31:0]               data;
    begin
        @(posedge clk);

        s_axi_awaddr  <= addr;
        s_axi_awprot  <= 3'b000;
        s_axi_awvalid <= 1'b1;

        s_axi_wdata   <= data;
        s_axi_wstrb   <= 4'hF;
        s_axi_wvalid  <= 1'b1;

        while (!s_axi_awready)
            @(posedge clk);
        @(posedge clk);
        s_axi_awvalid <= 1'b0;

        while (!s_axi_wready)
            @(posedge clk);
        @(posedge clk);
        s_axi_wvalid <= 1'b0;

        s_axi_bready <= 1'b1;
        while (!s_axi_bvalid)
            @(posedge clk);

        if (s_axi_bresp != 2'b00) begin
            $display("ERROR: AXI write response at address %h", addr);
            error_cnt = error_cnt + 1;
        end

        @(posedge clk);
        s_axi_bready <= 1'b0;
    end
endtask

// -----------------------------------------------------------------------------
// AXI4-Lite read
// -----------------------------------------------------------------------------
task automatic axi_read;
    input  [AXI_ADDR_WIDTH-1:0] addr;
    output [31:0]               data;
    begin
        @(posedge clk);

        s_axi_araddr  <= addr;
        s_axi_arprot  <= 3'b000;
        s_axi_arvalid <= 1'b1;

        while (!s_axi_arready)
            @(posedge clk);
        @(posedge clk);
        s_axi_arvalid <= 1'b0;

        s_axi_rready <= 1'b1;
        while (!s_axi_rvalid)
            @(posedge clk);

        data = s_axi_rdata;

        if (s_axi_rresp != 2'b00) begin
            $display("ERROR: AXI read response at address %h", addr);
            error_cnt = error_cnt + 1;
        end

        @(posedge clk);
        s_axi_rready <= 1'b0;
    end
endtask

