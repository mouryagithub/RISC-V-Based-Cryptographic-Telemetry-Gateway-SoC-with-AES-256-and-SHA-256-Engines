    s_axi_arprot  = 0;
    s_axi_arvalid = 0;

    s_axi_rready  = 0;

    repeat(4) @(posedge clk);

    // AXI reset is active LOW; AES cores use active HIGH reset.
    aresetn = 1'b1;
    rst     = 1'b0;

    repeat(20) @(posedge clk);

