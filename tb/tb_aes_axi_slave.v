        axi_write(8'h00, 32'h0001_0000);

        // Wait for AES cipher completion
        while (!cipher_done)
            @(posedge clk);

        // =============================================================
        // Read CIPHER TEXT_OUT0..3 through AXI
        // =============================================================
        axi_read(8'h34, rd);
        if (rd !== ciph[31:0]) begin
